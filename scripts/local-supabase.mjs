import { createHmac, randomBytes } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createServer } from 'node:net';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const supabaseDir = path.join(rootDir, 'supabase');
const frontendDir = path.join(rootDir, 'frontend');
const adminDir = path.join(rootDir, 'admin');
const backendDir = path.join(rootDir, 'backend');
const supabaseEnvPath = path.join(supabaseDir, '.env.local');
const frontendEnvPath = path.join(frontendDir, '.env.local');
const adminEnvPath = path.join(adminDir, '.env.local');
const composeFile = path.join(supabaseDir, 'docker-compose.local.yml');

function base64Url(value) {
  return Buffer.from(value).toString('base64url');
}

function signJwt(secret, payload) {
  const header = { alg: 'HS256', typ: 'JWT' };
  const now = Math.floor(Date.now() / 1000);
  const fullPayload = {
    iss: 'supabase',
    aud: 'authenticated',
    iat: now,
    exp: now + (10 * 365 * 24 * 60 * 60),
    ...payload,
  };

  const unsigned = `${base64Url(JSON.stringify(header))}.${base64Url(JSON.stringify(fullPayload))}`;
  const signature = createHmac('sha256', secret).update(unsigned).digest('base64url');
  return `${unsigned}.${signature}`;
}

function randomSecret(bytes = 32) {
  return randomBytes(bytes).toString('hex');
}

function parseEnv(content) {
  const result = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const idx = trimmed.indexOf('=');
    if (idx === -1) continue;
    result[trimmed.slice(0, idx)] = trimmed.slice(idx + 1);
  }
  return result;
}

async function readEnvFile(filePath) {
  if (!existsSync(filePath)) return {};
  return parseEnv(await readFile(filePath, 'utf8'));
}

function isPortFree(port) {
  return new Promise(resolve => {
    const server = createServer();
    server.unref();
    server.on('error', () => resolve(false));
    server.listen(port, '127.0.0.1', () => {
      server.close(() => resolve(true));
    });
  });
}

async function pickPort(preferred, fallbackPorts, allocated) {
  const candidates = [preferred, ...fallbackPorts].filter((value, index, array) => array.indexOf(value) === index);
  for (const port of candidates) {
    if (allocated.has(port)) continue;
    if (await isPortFree(port)) {
      allocated.add(port);
      return port;
    }
  }

  throw new Error(`Unable to find a free port for local Supabase (tried ${candidates.join(', ')})`);
}

async function ensureLocalEnvFiles() {
  const existing = await readEnvFile(supabaseEnvPath);
  const jwtSecret = existing.JWT_SECRET || randomSecret();
  const postgresPassword = existing.POSTGRES_PASSWORD || randomSecret(24);
  const anonKey = existing.ANON_KEY || signJwt(jwtSecret, { role: 'anon' });
  const serviceRoleKey = existing.SERVICE_ROLE_KEY || signJwt(jwtSecret, { role: 'service_role' });
  const adminEmail = existing.LOCAL_SUPABASE_ADMIN_EMAIL || 'admin@hlaupadagskra.local';
  const adminPassword = existing.LOCAL_SUPABASE_ADMIN_PASSWORD || randomSecret(16);
  const allocatedPorts = new Set();
  const dbPort = await pickPort(Number(existing.LOCAL_SUPABASE_DB_PORT) || 5432, [5433, 5434, 55432], allocatedPorts);
  const kongPort = await pickPort(Number(existing.LOCAL_SUPABASE_KONG_PORT) || 8000, [8001, 8002, 8003], allocatedPorts);
  const supabasePublicUrl = `http://localhost:${kongPort}`;

  const supabaseEnv = [
    '# Generated by `npm run supabase:setup`',
    `POSTGRES_PASSWORD=${postgresPassword}`,
    `JWT_SECRET=${jwtSecret}`,
    'JWT_EXPIRY=3600',
    `ANON_KEY=${anonKey}`,
    `SERVICE_ROLE_KEY=${serviceRoleKey}`,
    `LOCAL_SUPABASE_DB_PORT=${dbPort}`,
    `LOCAL_SUPABASE_KONG_PORT=${kongPort}`,
    `SUPABASE_PUBLIC_URL=${supabasePublicUrl}`,
    `API_EXTERNAL_URL=${supabasePublicUrl}`,
    'SITE_URL=http://localhost:5173',
    'ADDITIONAL_REDIRECT_URLS=http://localhost:5173,http://localhost:5174',
    `LOCAL_SUPABASE_ADMIN_EMAIL=${adminEmail}`,
    `LOCAL_SUPABASE_ADMIN_PASSWORD=${adminPassword}`,
    '',
  ].join('\n');

  const frontendEnv = [
    'VITE_API_URL=http://localhost:8080',
    `VITE_SUPABASE_URL=${supabasePublicUrl}`,
    `VITE_SUPABASE_ANON_KEY=${anonKey}`,
    'VITE_AUTH_REDIRECT_URL=http://localhost:5173',
    '',
  ].join('\n');

  const adminEnv = [
    'VITE_API_URL=http://localhost:8080',
    `VITE_SUPABASE_URL=${supabasePublicUrl}`,
    `VITE_SUPABASE_ANON_KEY=${anonKey}`,
    '',
  ].join('\n');

  await writeFile(supabaseEnvPath, supabaseEnv, 'utf8');
  await writeFile(frontendEnvPath, frontendEnv, 'utf8');
  await writeFile(adminEnvPath, adminEnv, 'utf8');

  return {
    jwtSecret,
    postgresPassword,
    anonKey,
    serviceRoleKey,
    dbPort,
    kongPort,
    supabasePublicUrl,
    apiExternalUrl: supabasePublicUrl,
    siteUrl: 'http://localhost:5173',
    redirectUrls: 'http://localhost:5173,http://localhost:5174',
    adminEmail,
    adminPassword,
  };
}

function runDockerCompose(args) {
  execFileSync('docker', ['compose', '--env-file', supabaseEnvPath, '-f', composeFile, ...args], {
    cwd: rootDir,
    stdio: 'inherit',
  });
}

function runDotnetUserSecrets(env) {
  const commonArgs = ['user-secrets', 'set'];
  execFileSync('dotnet', [...commonArgs, 'ConnectionStrings:DefaultConnection', `Host=localhost;Port=${env.dbPort};Database=postgres;Username=postgres;Password=${env.postgresPassword};Include Error Detail=true`], {
    cwd: backendDir,
    stdio: 'inherit',
  });
  execFileSync('dotnet', [...commonArgs, 'SUPABASE_URL', env.supabasePublicUrl], {
    cwd: backendDir,
    stdio: 'inherit',
  });
  execFileSync('dotnet', [...commonArgs, 'SUPABASE_JWT_SECRET', env.jwtSecret], {
    cwd: backendDir,
    stdio: 'inherit',
  });
}

async function waitForAuth(url, timeoutMs = 120000) {
  const started = Date.now();
  while (Date.now() - started < timeoutMs) {
    try {
      const response = await fetch(url, { cache: 'no-store' });
      if (response.ok) return;
    } catch {
      // keep waiting
    }
    await new Promise(resolve => setTimeout(resolve, 2000));
  }
  throw new Error(`Timed out waiting for Supabase auth at ${url}`);
}

async function seedAdminUser(env) {
  const response = await fetch(`${env.supabasePublicUrl}/auth/v1/admin/users`, {
    method: 'POST',
    headers: {
      apikey: env.serviceRoleKey,
      Authorization: `Bearer ${env.serviceRoleKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      email: env.adminEmail,
      password: env.adminPassword,
      email_confirm: true,
      app_metadata: { role: 'admin' },
    }),
  });

  if (response.ok) return;

  const body = await response.text();
  if (/already exists|already .* registered|duplicate|email_exists/i.test(body)) return;

  throw new Error(`Failed to seed admin user: ${response.status} ${body}`);
}

async function setup() {
  const env = await ensureLocalEnvFiles();
  runDockerCompose(['up', '-d']);
  await waitForAuth(`${env.supabasePublicUrl}/auth/v1/health`);
  await seedAdminUser(env);
  runDotnetUserSecrets(env);

  console.log('');
  console.log('Local Supabase is ready.');
  console.log(`Admin login: ${env.adminEmail}`);
  console.log(`Admin password: ${env.adminPassword}`);
  console.log('Frontend: http://localhost:5173');
  console.log('Admin: http://localhost:5174');
  console.log(`Supabase: ${env.supabasePublicUrl}`);
}

async function seed() {
  const env = await ensureLocalEnvFiles();
  await waitForAuth(`${env.supabasePublicUrl}/auth/v1/health`);
  await seedAdminUser(env);
  runDotnetUserSecrets(env);
  console.log('Local Supabase seeded.');
}

async function up() {
  await ensureLocalEnvFiles();
  runDockerCompose(['up', '-d']);
}

function down() {
  runDockerCompose(['down']);
}

const command = process.argv[2] || 'setup';

switch (command) {
  case 'setup':
    await setup();
    break;
  case 'seed':
    await seed();
    break;
  case 'up':
    await up();
    break;
  case 'down':
    down();
    break;
  default:
    console.error(`Unknown command: ${command}`);
    process.exitCode = 1;
}
